import { eq, exp, Numeric, setPrecision, string } from '../../src'

describe('exp', () => {
	setPrecision(12)

	const t = (expectation: Numeric, n: Numeric) => {
		it(`exp(${n}) = ${expectation}`, () => {
			const result = exp(n)
			expect(result.toString()).toBe(string(expectation))
			expect(eq(result, expectation)).toBe(true)
		})
	}

	t('1', 0)
	t('1', -0)
	t('2.718281828459', 1)
	t('7.389056098931', 2)
	t('0.367879441171', -1)
	t('0.135335283237', -2)
	t('1.6487212707', '0.5')
	t('0.000006144212', -12)
	t('0.00004539993', -10)
	t('0.000335462628', -8)
	t('0.00055308437', '-7.5')
	t('0.002478752177', -6)
	t('0.006737946999', -5)
	t('0.018315638889', -4)
	t('0.030197383422', '-3.5')
	t('0.049787068368', -3)
	t('0.082084998624', '-2.5')
	t('0.17377394345', '-1.75')
	t('0.223130160148', '-1.5')
	t('0.28650479686', '-1.25')
	t('0.472366552741', '-0.75')
	t('0.606530659713', '-0.5')
	t('0.778800783071', '-0.25')
	t('0.904837418036', '-0.1')
	t('0.990049833749', '-0.01')
	t('0.999999000001', '-0.000001')
	t('1.000001000001', '0.000001')
	t('1.010050167084', '0.01')
	t('1.105170918076', '0.1')
	t('1.284025416688', '0.25')
	t('2.117000016613', '0.75')
	t('3.490342957462', '1.25')
	t('4.481689070338', '1.5')
	t('5.754602676006', '1.75')
	// t('12.182493960703', '2.5')
	// t('33.115451958692', '3.5')
	// t('148.413159102577', 5)
})
